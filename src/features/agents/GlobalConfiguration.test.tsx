import { fireEvent, render, screen, waitFor, within } from "@testing-library/react"
import userEvent from "@testing-library/user-event"
import { beforeEach, describe, expect, it, vi } from "vitest"
import { ipc, IpcError } from "@/app/ipc"
import { ConfigurationTestProvider, mockConfigurationIpc, pageProps } from "@/features/settings/configuration.test-fixtures"
import { GlobalConfiguration } from "./GlobalConfiguration"

beforeEach(() => { mockConfigurationIpc() })
function panel(active = true, development = true) {
  const snapshot = { ...pageProps().session.snapshot!, development_tools_available: development }
  return <ConfigurationTestProvider snapshot={snapshot}><GlobalConfiguration active={active} /></ConfigurationTestProvider>
}

describe("即时应用的全局配置", () => {
  it("联网新闻配置按需读取、即时保存，与模型配置互不干扰", async () => {
    mockConfigurationIpc()
    render(panel())
    await screen.findByLabelText("模型名称", { selector: "input" })
    expect(ipc.getNewsConfiguration).not.toHaveBeenCalled()
    await userEvent.click(screen.getByRole("tab", { name: "联网新闻" }))
    await waitFor(() => expect(ipc.getNewsConfiguration).toHaveBeenCalledTimes(1))
    expect(screen.getByRole("combobox", { name: "新闻来源" })).toHaveTextContent("Google 新闻（中文搜索）")
    await userEvent.click(screen.getByRole("switch", { name: "启用联网新闻" }))
    await waitFor(() => expect(ipc.saveNewsConfiguration).toHaveBeenCalledTimes(1))
    expect(vi.mocked(ipc.saveNewsConfiguration).mock.lastCall?.[0].configuration.enabled).toBe(false)
    expect(ipc.saveGlobalConfiguration).not.toHaveBeenCalled()
  })
  it("文本只在失焦应用，配置请求剔除只读元数据，没有整页保存/读取", async () => {
    render(panel())
    const input = await screen.findByLabelText("模型名称", { selector: "input" })
    fireEvent.change(input, { target: { value: "新模型" } })
    expect(ipc.saveGlobalConfiguration).not.toHaveBeenCalled()
    fireEvent.blur(input)
    await waitFor(() => expect(ipc.saveGlobalConfiguration).toHaveBeenCalledTimes(1))
    const request = vi.mocked(ipc.saveGlobalConfiguration).mock.calls[0][0]
    expect(request.model_profiles[0].model_name).toBe("新模型")
    expect(request.model_profiles[0]).not.toHaveProperty("credential_configured")
    expect(request.model_profiles[0]).not.toHaveProperty("revision")
    expect(screen.queryByRole("button", { name: /保存|重新读取|丢弃/ })).not.toBeInTheDocument()
    expect(ipc.testModel).not.toHaveBeenCalled()
  })
  it("创建合法空模型预设立即持久化，未配置不能绑密钥或测试", async () => {
    render(panel())
    await screen.findByLabelText("模型名称", { selector: "input" })
    await userEvent.click(screen.getByRole("button", { name: "添加大模型" }))
    await waitFor(() => expect(ipc.saveGlobalConfiguration).toHaveBeenCalledTimes(1))
    const request = vi.mocked(ipc.saveGlobalConfiguration).mock.calls[0][0]
    expect(request.model_profiles[1]).toMatchObject({ name: "新模型预设", model_name: "", base_url: "" })
    const newModel = screen.getByRole("region", { name: "模型配置 新模型预设" })
    expect(within(newModel).getByLabelText("API 密钥", { selector: "input" })).toBeDisabled()
    expect(within(newModel).getByRole("button", { name: "测试模型是否可用" })).toBeDisabled()
  })
  it("人格文本的 check/cross 控件应用或还原，分类切换保留局部草稿", async () => {
    render(panel())
    await screen.findByLabelText("模型名称", { selector: "input" })
    await userEvent.click(screen.getByRole("tab", { name: "人格预设" }))
    const style = screen.getByLabelText("语言风格", { selector: "textarea" })
    await userEvent.click(style)
    fireEvent.change(style, { target: { value: "本次取消" } })
    await userEvent.click(screen.getByRole("button", { name: "撤销语言风格" }))
    expect(ipc.saveGlobalConfiguration).not.toHaveBeenCalled()
    fireEvent.change(style, { target: { value: "新风格" } })
    await userEvent.click(screen.getByRole("button", { name: "应用语言风格" }))
    await waitFor(() => expect(ipc.saveGlobalConfiguration).toHaveBeenCalledTimes(1))
    expect(vi.mocked(ipc.saveGlobalConfiguration).mock.calls[0][0].persona_presets[0].language_style).toBe("新风格")
    const name = screen.getByLabelText("人格名称", { selector: "input" })
    fireEvent.change(name, { target: { value: "分类间草稿" } })
    await userEvent.click(screen.getByRole("tab", { name: "模型配置" }))
    await userEvent.click(screen.getByRole("tab", { name: "人格预设" }))
    expect(screen.getByLabelText("人格名称", { selector: "input" })).toHaveValue("分类间草稿")
  })
  it("人格预设的活跃度立即应用且不改变其他人格维度", async () => {
    const data = mockConfigurationIpc()
    const originalDimensions = { ...data.global.persona_presets[0].dimensions }
    render(panel())
    await screen.findByLabelText("模型名称", { selector: "input" })
    await userEvent.click(screen.getByRole("tab", { name: "人格预设" }))
    await userEvent.click(screen.getByText("八个人格维度（0–100）"))
    const activity = screen.getByRole("spinbutton", { name: "活跃度" })
    fireEvent.change(activity, { target: { value: "88" } })
    fireEvent.blur(activity)
    await waitFor(() => expect(ipc.saveGlobalConfiguration).toHaveBeenCalledTimes(1))
    expect(vi.mocked(ipc.saveGlobalConfiguration).mock.lastCall?.[0].persona_presets[0].dimensions).toEqual({ ...originalDimensions, activity: 88 })
    expect(ipc.controlAgentRuntime).not.toHaveBeenCalled()
  })
  it("删除需对话框确认，取消不写入；确认后人格独立副本不受影响", async () => {
    render(panel())
    await screen.findByLabelText("模型名称", { selector: "input" })
    await userEvent.click(screen.getByRole("button", { name: "删除大模型" }))
    const modelDialog = await screen.findByRole("dialog")
    expect(within(modelDialog).getByText(/需先解除或更换成员的模型配置/)).toBeInTheDocument()
    expect(ipc.saveGlobalConfiguration).not.toHaveBeenCalled()
    await userEvent.click(within(modelDialog).getByRole("button", { name: "取消" }))
    await userEvent.click(screen.getByRole("tab", { name: "人格预设" }))
    await userEvent.click(screen.getByRole("button", { name: "删除人格预设" }))
    const personaDialog = await screen.findByRole("dialog")
    expect(within(personaDialog).getByText(/成员已经复制的独立人格配置不受影响/)).toBeInTheDocument()
    await userEvent.click(within(personaDialog).getByRole("button", { name: "确认删除" }))
    await waitFor(() => expect(ipc.saveGlobalConfiguration).toHaveBeenCalledTimes(1))
    expect(vi.mocked(ipc.saveGlobalConfiguration).mock.calls[0][0].persona_presets).toEqual([])
  })
  it("失败保留 applied 参数，局部重试应用复用请求 ID", async () => {
    vi.mocked(ipc.saveGlobalConfiguration).mockRejectedValueOnce(new IpcError({ code: "INTERNAL_ERROR", message: "应用失败", retryability: "after_user_action", field_path: null, trace_id: "t", may_have_been_charged: false }))
    render(panel())
    const input = await screen.findByLabelText("模型名称", { selector: "input" })
    fireEvent.change(input, { target: { value: "保留参数" } })
    fireEvent.blur(input)
    await screen.findByRole("button", { name: "重试应用" })
    expect(input).toHaveValue("保留参数")
    await userEvent.click(screen.getByRole("button", { name: "重试应用" }))
    await waitFor(() => expect(ipc.saveGlobalConfiguration).toHaveBeenCalledTimes(2))
    expect(vi.mocked(ipc.saveGlobalConfiguration).mock.calls[0][0].client_request_id).toBe(vi.mocked(ipc.saveGlobalConfiguration).mock.calls[1][0].client_request_id)
    await waitFor(() => expect(screen.queryByRole("button", { name: "重试应用" })).not.toBeInTheDocument())
  })
  it("密钥失焦应用的 barrier 刷新 revision 后，后续文本用新版本写入", async () => {
    render(panel())
    const key = await screen.findByLabelText("API 密钥", { selector: "input" })
    fireEvent.change(key, { target: { value: "private-test-key" } })
    fireEvent.blur(key)
    expect(key).toHaveValue("")
    await screen.findByText("密钥已应用到系统凭据库，输入已清空。")
    expect(screen.getByPlaceholderText("已配置系统密钥")).toBeInTheDocument()
    const model = screen.getByLabelText("模型名称", { selector: "input" })
    fireEvent.change(model, { target: { value: "新模型" } })
    fireEvent.blur(model)
    await waitFor(() => expect(ipc.saveGlobalConfiguration).toHaveBeenCalledTimes(1))
    expect(vi.mocked(ipc.saveGlobalConfiguration).mock.lastCall?.[0].expected_revision).toBe("2")
    expect(ipc.getGlobalConfiguration).toHaveBeenCalledTimes(2)
    expect(ipc.secretStatus).not.toHaveBeenCalled()
    expect(document.body).not.toHaveTextContent("private-test-key")
  })
  it("地址校验拒绝凭据/查询/非本机HTTP，但空地址可持久化为未配置", async () => {
    render(panel())
    const input = await screen.findByLabelText("API 地址", { selector: "input" })
    for (const url of ["https://private-key@example.com/v1", "https://example.com/v1?key=private-key", "http://remote.example.com/v1"]) {
      fireEvent.change(input, { target: { value: url } })
      fireEvent.blur(input)
      expect(ipc.saveGlobalConfiguration).not.toHaveBeenCalled()
    }
    fireEvent.change(input, { target: { value: "" } })
    fireEvent.blur(input)
    await waitFor(() => expect(ipc.saveGlobalConfiguration).toHaveBeenCalledTimes(1))
    expect(vi.mocked(ipc.saveGlobalConfiguration).mock.lastCall?.[0].model_profiles[0].base_url).toBe("")
    expect(screen.getByRole("button", { name: "测试模型是否可用" })).toBeDisabled()
  })
  it("开发导入按 snapshot 能力显示图标，移除项不再展示", async () => {
    const hidden = render(panel(true, false))
    await screen.findByLabelText("模型名称", { selector: "input" })
    expect(screen.queryByRole("button", { name: "导入开发环境大模型" })).not.toBeInTheDocument()
    expect(screen.getByRole("button", { name: "添加大模型" })).toBeInTheDocument()
    expect(screen.queryByText("生成参数与预算")).not.toBeInTheDocument()
    expect(screen.queryByLabelText("称呼用语")).not.toBeInTheDocument()
    expect(screen.queryByLabelText("角色指令（SKILL）")).not.toBeInTheDocument()
    hidden.unmount()
    render(panel(true, true))
    expect(await screen.findByRole("button", { name: "导入开发环境大模型" })).toBeInTheDocument()
  })
})
